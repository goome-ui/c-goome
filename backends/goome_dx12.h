typedef struct {
    ID3D12Resource *r;
    int left;
} gm_dx12_dead;

typedef struct {
    goome *g;
    ID3D12Device *dev;
    ID3D12DescriptorHeap *heap;
    D3D12_CPU_DESCRIPTOR_HANDLE cpu;
    D3D12_GPU_DESCRIPTOR_HANDLE gpu;
    ID3D12RootSignature *root;
    ID3D12PipelineState *pso;
    ID3D12Resource *tex, *up[8];
    unsigned char *mem[8];
    int n, cur, tw, th, fresh;
    gm_dx12_dead dead[96];
} gm_dx12;

static gm_dx12 gm_dx12_all[8];

static gm_dx12 *gm_dx12_find(goome *g)
{
    for (int i = 0; i < 8; i++)
        if (g && gm_dx12_all[i].g == g) return &gm_dx12_all[i];
    return NULL;
}

static void gm_dx12_bury(gm_dx12 *d, ID3D12Resource *r)
{
    if (!r) return;
    for (int i = 0; i < 96; i++)
        if (!d->dead[i].r) {
            d->dead[i].r = r, d->dead[i].left = d->n + 1;
            return;
        }
    GM_COM0(r, Release);
}

static void gm_dx12_drop_tex(gm_dx12 *d)
{
    gm_dx12_bury(d, d->tex);
    d->tex = NULL;
    for (int i = 0; i < d->n; i++) {
        gm_dx12_bury(d, d->up[i]);
        d->up[i] = NULL, d->mem[i] = NULL;
    }
    d->tw = d->th = 0;
}

static ID3D12Resource *gm_dx12_resource(gm_dx12 *d, D3D12_HEAP_TYPE heap, const D3D12_RESOURCE_DESC *rd, D3D12_RESOURCE_STATES state)
{
    D3D12_HEAP_PROPERTIES hp;
    memset(&hp, 0, sizeof(hp));
    hp.Type = heap;
    ID3D12Resource *r = NULL;
    if (FAILED(GM_COM(d->dev, CreateCommittedResource, &hp, D3D12_HEAP_FLAG_NONE, rd, state, NULL, GM_REF(gm_dx12_iid_res), (void **)&r))) return NULL;
    return r;
}

static int gm_dx12_make_tex(gm_dx12 *d, int w, int h)
{
    gm_dx12_drop_tex(d);
    D3D12_RESOURCE_DESC rd;
    memset(&rd, 0, sizeof(rd));
    rd.Dimension = D3D12_RESOURCE_DIMENSION_TEXTURE2D, rd.Width = (UINT64)w, rd.Height = (UINT)h;
    rd.DepthOrArraySize = 1, rd.MipLevels = 1, rd.Format = DXGI_FORMAT_B8G8R8A8_UNORM, rd.SampleDesc.Count = 1;
    d->tex = gm_dx12_resource(d, D3D12_HEAP_TYPE_DEFAULT, &rd, D3D12_RESOURCE_STATE_COPY_DEST);
    memset(&rd, 0, sizeof(rd));
    rd.Dimension = D3D12_RESOURCE_DIMENSION_BUFFER, rd.Width = (UINT64)((w * 4 + 255) & ~255) * (UINT64)h;
    rd.Height = 1, rd.DepthOrArraySize = 1, rd.MipLevels = 1, rd.SampleDesc.Count = 1, rd.Layout = D3D12_TEXTURE_LAYOUT_ROW_MAJOR;
    int ok = d->tex != NULL;
    for (int i = 0; i < d->n && ok; i++) {
        D3D12_RANGE none = {0, 0};
        void *p = NULL;
        d->up[i] = gm_dx12_resource(d, D3D12_HEAP_TYPE_UPLOAD, &rd, D3D12_RESOURCE_STATE_GENERIC_READ);
        ok = d->up[i] && SUCCEEDED(GM_COM(d->up[i], Map, 0, &none, &p));
        d->mem[i] = (unsigned char *)p;
    }
    if (!ok) {
        gm_dx12_drop_tex(d);
        return GOOME_ENOMEM;
    }
    D3D12_SHADER_RESOURCE_VIEW_DESC sd;
    memset(&sd, 0, sizeof(sd));
    sd.Format = DXGI_FORMAT_B8G8R8A8_UNORM, sd.ViewDimension = D3D12_SRV_DIMENSION_TEXTURE2D;
    sd.Shader4ComponentMapping = D3D12_DEFAULT_SHADER_4_COMPONENT_MAPPING, sd.Texture2D.MipLevels = 1;
    GM_COM(d->dev, CreateShaderResourceView, d->tex, &sd, d->cpu);
    d->tw = w, d->th = h, d->fresh = 1, d->cur = 0;
    return GOOME_OK;
}

int goome_dx12_init(goome *g, ID3D12Device *dev, int frames_in_flight, DXGI_FORMAT rtv_format, ID3D12DescriptorHeap *srv_heap, D3D12_CPU_DESCRIPTOR_HANDLE srv_cpu, D3D12_GPU_DESCRIPTOR_HANDLE srv_gpu)
{
    if (!g || !dev || !srv_heap || frames_in_flight < 1 || frames_in_flight > 8) return GOOME_EARG;
    if (gm_dx12_find(g)) return GOOME_OK;
    gm_dx12 *d = NULL;
    for (int i = 0; i < 8 && !d; i++)
        if (!gm_dx12_all[i].g) d = &gm_dx12_all[i];
    if (!d) return GOOME_ENOMEM;
    HMODULE lib = GetModuleHandleA("d3d12.dll");
    if (!lib) lib = LoadLibraryA("d3d12.dll");
    PFN_D3D12_SERIALIZE_ROOT_SIGNATURE ser = lib ? (PFN_D3D12_SERIALIZE_ROOT_SIGNATURE)(void (*)(void))GetProcAddress(lib, "D3D12SerializeRootSignature") : NULL;
    if (!ser) return GOOME_ENOTSUP;
    memset(d, 0, sizeof(*d));
    d->dev = dev, d->heap = srv_heap, d->cpu = srv_cpu, d->gpu = srv_gpu, d->n = frames_in_flight;

    D3D12_DESCRIPTOR_RANGE range;
    memset(&range, 0, sizeof(range));
    range.RangeType = D3D12_DESCRIPTOR_RANGE_TYPE_SRV, range.NumDescriptors = 1;
    D3D12_ROOT_PARAMETER param;
    memset(&param, 0, sizeof(param));
    param.ParameterType = D3D12_ROOT_PARAMETER_TYPE_DESCRIPTOR_TABLE, param.ShaderVisibility = D3D12_SHADER_VISIBILITY_PIXEL;
    param.DescriptorTable.NumDescriptorRanges = 1, param.DescriptorTable.pDescriptorRanges = &range;
    D3D12_ROOT_SIGNATURE_DESC rs;
    memset(&rs, 0, sizeof(rs));
    rs.NumParameters = 1, rs.pParameters = &param;
    ID3DBlob *blob = NULL, *err = NULL;
    HRESULT hr = ser(&rs, D3D_ROOT_SIGNATURE_VERSION_1, &blob, &err);
    GM_REL(err);
    if (FAILED(hr)) return GOOME_ENOTSUP;
    hr = GM_COM(dev, CreateRootSignature, 0, GM_COM0(blob, GetBufferPointer), GM_COM0(blob, GetBufferSize), GM_REF(gm_dx12_iid_root), (void **)&d->root);
    GM_REL(blob);
    if (FAILED(hr)) return GOOME_ENOTSUP;

    D3D12_GRAPHICS_PIPELINE_STATE_DESC pd;
    memset(&pd, 0, sizeof(pd));
    pd.pRootSignature = d->root;
    pd.VS.pShaderBytecode = gm_dx12_vs, pd.VS.BytecodeLength = sizeof(gm_dx12_vs);
    pd.PS.pShaderBytecode = gm_dx12_ps, pd.PS.BytecodeLength = sizeof(gm_dx12_ps);
    D3D12_RENDER_TARGET_BLEND_DESC *b = &pd.BlendState.RenderTarget[0];
    b->BlendEnable = TRUE, b->SrcBlend = b->SrcBlendAlpha = D3D12_BLEND_ONE, b->DestBlend = b->DestBlendAlpha = D3D12_BLEND_INV_SRC_ALPHA;
    b->BlendOp = b->BlendOpAlpha = D3D12_BLEND_OP_ADD, b->LogicOp = D3D12_LOGIC_OP_NOOP, b->RenderTargetWriteMask = D3D12_COLOR_WRITE_ENABLE_ALL;
    pd.SampleMask = 0xFFFFFFFFu;
    pd.RasterizerState.FillMode = D3D12_FILL_MODE_SOLID, pd.RasterizerState.CullMode = D3D12_CULL_MODE_NONE, pd.RasterizerState.DepthClipEnable = TRUE;
    pd.DepthStencilState.DepthFunc = D3D12_COMPARISON_FUNC_ALWAYS;
    pd.PrimitiveTopologyType = D3D12_PRIMITIVE_TOPOLOGY_TYPE_TRIANGLE;
    pd.NumRenderTargets = 1, pd.RTVFormats[0] = rtv_format, pd.SampleDesc.Count = 1;
    if (FAILED(GM_COM(dev, CreateGraphicsPipelineState, &pd, GM_REF(gm_dx12_iid_pso), (void **)&d->pso))) {
        GM_REL(d->root);
        return GOOME_ENOTSUP;
    }
    GM_COM0(dev, AddRef);
    GM_COM0(srv_heap, AddRef);
    d->g = g;
    return GOOME_OK;
}

static void gm_dx12_barrier(ID3D12GraphicsCommandList *cl, ID3D12Resource *r, D3D12_RESOURCE_STATES from, D3D12_RESOURCE_STATES to)
{
    D3D12_RESOURCE_BARRIER b;
    memset(&b, 0, sizeof(b));
    b.Type = D3D12_RESOURCE_BARRIER_TYPE_TRANSITION;
    b.Transition.pResource = r, b.Transition.Subresource = D3D12_RESOURCE_BARRIER_ALL_SUBRESOURCES;
    b.Transition.StateBefore = from, b.Transition.StateAfter = to;
    GM_COM(cl, ResourceBarrier, 1, &b);
}

void goome_dx12_render(goome *g, ID3D12GraphicsCommandList *cl)
{
    gm_dx12 *d = gm_dx12_find(g);
    goome_image f;
    if (!d || !cl) return;
    for (int i = 0; i < 96; i++)
        if (d->dead[i].r && --d->dead[i].left <= 0) GM_REL(d->dead[i].r);
    if (goome_frame(g, &f) != GOOME_OK || f.w <= 0 || f.h <= 0) return;
    goome_rect r;
    int dirty = goome_frame_dirty(g, &r);
    if (!d->tex || f.w != d->tw || f.h != d->th) {
        if (gm_dx12_make_tex(d, f.w, f.h) != GOOME_OK) return;
    }
    if (d->fresh) r.x = r.y = 0, r.w = f.w, r.h = f.h, dirty = 1;
    if (dirty) {
        UINT pitch = (UINT)(r.w * 4 + 255) & ~255u;
        goome_frame_copy(g, d->mem[d->cur], (int)pitch, GOOME_FMT_BGRA_PREMUL, &r);
        D3D12_TEXTURE_COPY_LOCATION dst, src;
        memset(&dst, 0, sizeof(dst));
        memset(&src, 0, sizeof(src));
        dst.pResource = d->tex, dst.Type = D3D12_TEXTURE_COPY_TYPE_SUBRESOURCE_INDEX;
        src.pResource = d->up[d->cur], src.Type = D3D12_TEXTURE_COPY_TYPE_PLACED_FOOTPRINT;
        src.PlacedFootprint.Footprint.Format = DXGI_FORMAT_B8G8R8A8_UNORM;
        src.PlacedFootprint.Footprint.Width = (UINT)r.w, src.PlacedFootprint.Footprint.Height = (UINT)r.h;
        src.PlacedFootprint.Footprint.Depth = 1, src.PlacedFootprint.Footprint.RowPitch = pitch;
        if (!d->fresh) gm_dx12_barrier(cl, d->tex, D3D12_RESOURCE_STATE_PIXEL_SHADER_RESOURCE, D3D12_RESOURCE_STATE_COPY_DEST);
        GM_COM(cl, CopyTextureRegion, &dst, (UINT)r.x, (UINT)r.y, 0, &src, NULL);
        gm_dx12_barrier(cl, d->tex, D3D12_RESOURCE_STATE_COPY_DEST, D3D12_RESOURCE_STATE_PIXEL_SHADER_RESOURCE);
        d->cur = (d->cur + 1) % d->n, d->fresh = 0;
    }
    D3D12_VIEWPORT vp = {0, 0, (FLOAT)d->tw, (FLOAT)d->th, 0, 1};
    D3D12_RECT sc = {0, 0, d->tw, d->th};
    GM_COM(cl, SetGraphicsRootSignature, d->root);
    GM_COM(cl, SetPipelineState, d->pso);
    GM_COM(cl, SetDescriptorHeaps, 1, &d->heap);
    GM_COM(cl, SetGraphicsRootDescriptorTable, 0, d->gpu);
    GM_COM(cl, IASetPrimitiveTopology, D3D_PRIMITIVE_TOPOLOGY_TRIANGLESTRIP);
    GM_COM(cl, RSSetViewports, 1, &vp);
    GM_COM(cl, RSSetScissorRects, 1, &sc);
    GM_COM(cl, DrawInstanced, 4, 1, 0, 0);
}

void goome_dx12_resize(goome *g, int w, int h, double scale)
{
    gm_dx12 *d = gm_dx12_find(g);
    if (goome_resize(g, w, h, scale) == GOOME_OK && d) gm_dx12_drop_tex(d);
}

void goome_dx12_shutdown(goome *g)
{
    gm_dx12 *d = gm_dx12_find(g);
    if (!d) return;
    GM_REL(d->tex);
    for (int i = 0; i < 8; i++) GM_REL(d->up[i]);
    for (int i = 0; i < 96; i++) GM_REL(d->dead[i].r);
    GM_REL(d->pso), GM_REL(d->root), GM_REL(d->heap), GM_REL(d->dev);
    memset(d, 0, sizeof(*d));
}

