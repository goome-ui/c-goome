typedef struct {
    goome *g;
    ID3D11Device *dev;
    ID3D11DeviceContext *ctx;
    ID3D11VertexShader *vs;
    ID3D11PixelShader *ps;
    ID3D11BlendState *blend;
    ID3D11RasterizerState *rs;
    ID3D11DepthStencilState *ds;
    ID3D11Texture2D *tex;
    ID3D11ShaderResourceView *srv;
    int tw, th;
} gm_dx11;

static gm_dx11 gm_dx11_all[8];

static gm_dx11 *gm_dx11_find(goome *g)
{
    for (int i = 0; i < 8; i++)
        if (g && gm_dx11_all[i].g == g) return &gm_dx11_all[i];
    return NULL;
}

static void gm_dx11_drop_tex(gm_dx11 *d)
{
    GM_REL(d->srv);
    GM_REL(d->tex);
    d->tw = d->th = 0;
}

static int gm_dx11_make_tex(gm_dx11 *d, const goome_image *f)
{
    gm_dx11_drop_tex(d);
    D3D11_TEXTURE2D_DESC td;
    memset(&td, 0, sizeof(td));
    td.Width = (UINT)f->w, td.Height = (UINT)f->h, td.MipLevels = 1, td.ArraySize = 1;
    td.Format = DXGI_FORMAT_B8G8R8A8_UNORM, td.SampleDesc.Count = 1;
    td.Usage = D3D11_USAGE_DEFAULT, td.BindFlags = D3D11_BIND_SHADER_RESOURCE;
    D3D11_SUBRESOURCE_DATA init = {f->px, (UINT)f->stride * 4, 0};
    if (FAILED(GM_COM(d->dev, CreateTexture2D, &td, &init, &d->tex))) return GOOME_ENOMEM;
    if (FAILED(GM_COM(d->dev, CreateShaderResourceView, (ID3D11Resource *)d->tex, NULL, &d->srv))) {
        gm_dx11_drop_tex(d);
        return GOOME_ENOMEM;
    }
    d->tw = f->w, d->th = f->h;
    return GOOME_OK;
}

int goome_dx11_init(goome *g, ID3D11Device *dev, ID3D11DeviceContext *ctx)
{
    if (!g || !dev || !ctx) return GOOME_EARG;
    if (gm_dx11_find(g)) return GOOME_OK;
    gm_dx11 *d = NULL;
    for (int i = 0; i < 8 && !d; i++)
        if (!gm_dx11_all[i].g) d = &gm_dx11_all[i];
    if (!d) return GOOME_ENOMEM;
    memset(d, 0, sizeof(*d));
    d->dev = dev, d->ctx = ctx;
    D3D11_BLEND_DESC bd;
    memset(&bd, 0, sizeof(bd));
    bd.RenderTarget[0].BlendEnable = TRUE;
    bd.RenderTarget[0].SrcBlend = bd.RenderTarget[0].SrcBlendAlpha = D3D11_BLEND_ONE;
    bd.RenderTarget[0].DestBlend = bd.RenderTarget[0].DestBlendAlpha = D3D11_BLEND_INV_SRC_ALPHA;
    bd.RenderTarget[0].BlendOp = bd.RenderTarget[0].BlendOpAlpha = D3D11_BLEND_OP_ADD;
    bd.RenderTarget[0].RenderTargetWriteMask = D3D11_COLOR_WRITE_ENABLE_ALL;
    D3D11_RASTERIZER_DESC rd;
    memset(&rd, 0, sizeof(rd));
    rd.FillMode = D3D11_FILL_SOLID, rd.CullMode = D3D11_CULL_NONE, rd.DepthClipEnable = TRUE;
    D3D11_DEPTH_STENCIL_DESC dd;
    memset(&dd, 0, sizeof(dd));
    dd.DepthWriteMask = D3D11_DEPTH_WRITE_MASK_ZERO, dd.DepthFunc = D3D11_COMPARISON_ALWAYS;
    dd.FrontFace.StencilFunc = dd.BackFace.StencilFunc = D3D11_COMPARISON_ALWAYS;
    if (FAILED(GM_COM(dev, CreateVertexShader, gm_dx11_vs, sizeof(gm_dx11_vs), NULL, &d->vs)) ||
        FAILED(GM_COM(dev, CreatePixelShader, gm_dx11_ps, sizeof(gm_dx11_ps), NULL, &d->ps)) ||
        FAILED(GM_COM(dev, CreateBlendState, &bd, &d->blend)) || FAILED(GM_COM(dev, CreateRasterizerState, &rd, &d->rs)) ||
        FAILED(GM_COM(dev, CreateDepthStencilState, &dd, &d->ds))) {
        GM_REL(d->vs), GM_REL(d->ps), GM_REL(d->blend), GM_REL(d->rs), GM_REL(d->ds);
        return GOOME_ENOTSUP;
    }
    GM_COM0(dev, AddRef);
    GM_COM0(ctx, AddRef);
    d->g = g;
    return GOOME_OK;
}

void goome_dx11_render(goome *g)
{
    gm_dx11 *d = gm_dx11_find(g);
    goome_image f;
    if (!d || goome_frame(g, &f) != GOOME_OK || f.w <= 0 || f.h <= 0) return;
    ID3D11DeviceContext *c = d->ctx;
    goome_rect r;
    int dirty = goome_frame_dirty(g, &r);
    if (!d->tex || f.w != d->tw || f.h != d->th) {
        if (gm_dx11_make_tex(d, &f) != GOOME_OK) return;
    } else if (dirty) {
        D3D11_BOX box = {(UINT)r.x, (UINT)r.y, 0, (UINT)(r.x + r.w), (UINT)(r.y + r.h), 1};
        GM_COM(c, UpdateSubresource, (ID3D11Resource *)d->tex, 0, &box, f.px + (size_t)r.y * f.stride + r.x, (UINT)f.stride * 4, 0);
    }

    UINT nvp = D3D11_VIEWPORT_AND_SCISSORRECT_OBJECT_COUNT_PER_PIPELINE, nps = 256, nvs = 256, ngs = 256, nhs = 256, nds = 256;
    D3D11_VIEWPORT vps[D3D11_VIEWPORT_AND_SCISSORRECT_OBJECT_COUNT_PER_PIPELINE];
    ID3D11RasterizerState *rs = NULL;
    ID3D11BlendState *blend = NULL;
    FLOAT factor[4];
    UINT mask, sref;
    ID3D11DepthStencilState *ds = NULL;
    ID3D11ShaderResourceView *srv = NULL;
    ID3D11PixelShader *ps = NULL;
    ID3D11VertexShader *vs = NULL;
    ID3D11GeometryShader *gs = NULL;
    ID3D11HullShader *hs = NULL;
    ID3D11DomainShader *dsh = NULL;
    ID3D11ClassInstance *psi[256], *vsi[256], *gsi[256], *hsi[256], *dsi[256];
    D3D11_PRIMITIVE_TOPOLOGY topo;
    ID3D11InputLayout *layout = NULL;
    GM_COM(c, RSGetViewports, &nvp, vps);
    GM_COM(c, RSGetState, &rs);
    GM_COM(c, OMGetBlendState, &blend, factor, &mask);
    GM_COM(c, OMGetDepthStencilState, &ds, &sref);
    GM_COM(c, PSGetShaderResources, 0, 1, &srv);
    GM_COM(c, PSGetShader, &ps, psi, &nps);
    GM_COM(c, VSGetShader, &vs, vsi, &nvs);
    GM_COM(c, GSGetShader, &gs, gsi, &ngs);
    GM_COM(c, HSGetShader, &hs, hsi, &nhs);
    GM_COM(c, DSGetShader, &dsh, dsi, &nds);
    GM_COM(c, IAGetPrimitiveTopology, &topo);
    GM_COM(c, IAGetInputLayout, &layout);

    D3D11_VIEWPORT vp = {0, 0, (FLOAT)d->tw, (FLOAT)d->th, 0, 1};
    static const FLOAT zero[4] = {0, 0, 0, 0};
    GM_COM(c, RSSetViewports, 1, &vp);
    GM_COM(c, RSSetState, d->rs);
    GM_COM(c, OMSetBlendState, d->blend, zero, 0xFFFFFFFFu);
    GM_COM(c, OMSetDepthStencilState, d->ds, 0);
    GM_COM(c, PSSetShaderResources, 0, 1, &d->srv);
    GM_COM(c, PSSetShader, d->ps, NULL, 0);
    GM_COM(c, VSSetShader, d->vs, NULL, 0);
    GM_COM(c, GSSetShader, NULL, NULL, 0);
    GM_COM(c, HSSetShader, NULL, NULL, 0);
    GM_COM(c, DSSetShader, NULL, NULL, 0);
    GM_COM(c, IASetPrimitiveTopology, D3D11_PRIMITIVE_TOPOLOGY_TRIANGLESTRIP);
    GM_COM(c, IASetInputLayout, NULL);
    GM_COM(c, Draw, 4, 0);

    GM_COM(c, RSSetViewports, nvp, vps);
    GM_COM(c, RSSetState, rs);
    GM_COM(c, OMSetBlendState, blend, factor, mask);
    GM_COM(c, OMSetDepthStencilState, ds, sref);
    GM_COM(c, PSSetShaderResources, 0, 1, &srv);
    GM_COM(c, PSSetShader, ps, psi, nps);
    GM_COM(c, VSSetShader, vs, vsi, nvs);
    GM_COM(c, GSSetShader, gs, gsi, ngs);
    GM_COM(c, HSSetShader, hs, hsi, nhs);
    GM_COM(c, DSSetShader, dsh, dsi, nds);
    GM_COM(c, IASetPrimitiveTopology, topo);
    GM_COM(c, IASetInputLayout, layout);
    GM_REL(rs), GM_REL(blend), GM_REL(ds), GM_REL(srv), GM_REL(ps), GM_REL(vs), GM_REL(gs), GM_REL(hs), GM_REL(dsh), GM_REL(layout);
    for (UINT i = 0; i < nps; i++) GM_REL(psi[i]);
    for (UINT i = 0; i < nvs; i++) GM_REL(vsi[i]);
    for (UINT i = 0; i < ngs; i++) GM_REL(gsi[i]);
    for (UINT i = 0; i < nhs; i++) GM_REL(hsi[i]);
    for (UINT i = 0; i < nds; i++) GM_REL(dsi[i]);
}

void goome_dx11_resize(goome *g, int w, int h, double scale)
{
    gm_dx11 *d = gm_dx11_find(g);
    if (goome_resize(g, w, h, scale) == GOOME_OK && d) gm_dx11_drop_tex(d);
}

void goome_dx11_shutdown(goome *g)
{
    gm_dx11 *d = gm_dx11_find(g);
    if (!d) return;
    gm_dx11_drop_tex(d);
    GM_REL(d->vs), GM_REL(d->ps), GM_REL(d->blend), GM_REL(d->rs), GM_REL(d->ds);
    GM_REL(d->ctx), GM_REL(d->dev);
    memset(d, 0, sizeof(*d));
}

